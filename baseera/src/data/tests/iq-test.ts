/**
 * «اختبار الذكاء IQ» — عيّنة استدلال بلا رقم ذكاء.
 *
 * هذه أصدق صفحة في المنصّة وأصعبها تجارياً. الناس يبحثون عن «رقم IQ»،
 * ولا يوجد اختبار من اثني عشر سؤالاً على الإنترنت يستطيع إعطاءه: رقم
 * الذكاء يحتاج بنوداً مُعايرة على عيّنة ممثّلة، واختباراً مقنّناً بإشراف
 * مختصّ. كل موقع يعطيك «IQ 127» بعد عشرة أسئلة يخترع الرقم.
 *
 * البنود أصلية، على طراز أنواع البنود في ICAR (International Cognitive
 * Ability Resource، ملك عام): سلاسل رقمية وحرفية، ومقارنات لفظية،
 * واستدلال منطقي، ومصفوفات. ولم يُقَس ثباتها بعد، فلا نعرض نطاق ثقة —
 * لأن اختراع ثبات أسوأ من غيابه.
 *
 * المصفوفات مصمَّمة لتعمل في الاتّجاهين: قاعدتها «كل صفّ وعمود يحوي كل
 * عنصر مرّة»، فلا يتغيّر الحلّ إن قُرئت من اليمين أو اليسار. مصفوفات
 * رافن التقليدية تُقرأ من اليسار، وهذا يظلم القارئ العربي بلا سبب.
 */

type Shape = 'circle' | 'square' | 'triangle';
type Fill = 'none' | 'light' | 'solid';

function shape( kind: Shape, cx: number, cy: number, r: number, fill: Fill ): string {
	const f = fill === 'solid' ? 'currentColor' : fill === 'light' ? 'currentColor' : 'none';
	const op = fill === 'light' ? ' fill-opacity=".3"' : '';
	const common = `fill="${ f }"${ op } stroke="currentColor" stroke-width="2.4"`;

	if ( kind === 'circle' ) {
		return `<circle cx="${ cx }" cy="${ cy }" r="${ r }" ${ common }/>`;
	}

	if ( kind === 'square' ) {
		return `<rect x="${ cx - r }" y="${ cy - r }" width="${ r * 2 }" height="${ r * 2 }" rx="2" ${ common }/>`;
	}

	return `<path d="M${ cx } ${ cy - r - 1 }L${ cx + r + 2 } ${ cy + r }H${ cx - r - 2 }Z" stroke-linejoin="round" ${ common }/>`;
}

function dots( n: number, cx: number, cy: number ): string {
	const pos: Record<number, [ number, number ][]> = {
		2: [ [ -10, 0 ], [ 10, 0 ] ],
		3: [ [ 0, -11 ], [ -11, 9 ], [ 11, 9 ] ],
		4: [ [ -10, -10 ], [ 10, -10 ], [ -10, 10 ], [ 10, 10 ] ],
		5: [ [ -12, -12 ], [ 12, -12 ], [ 0, 0 ], [ -12, 12 ], [ 12, 12 ] ],
	};

	return ( pos[ n ] ?? [] ).map( ( [ x, y ] ) => `<circle cx="${ cx + x }" cy="${ cy + y }" r="5.5" fill="currentColor"/>` ).join( '' );
}

/**
 * يرسم مصفوفة 3×3. الخلايا بترتيب القراءة العربية: الأولى يميناً،
 * والخلية الناقصة آخر الصفّ الأخير — أي أسفل اليسار.
 */
function grid( cells: ( ( cx: number, cy: number ) => string )[], label: string ): string {
	const size = 66;
	const gap = 6;
	let body = '';

	cells.forEach( ( draw, i ) => {
		const row = Math.floor( i / 3 );
		const colRtl = i % 3;
		const x = ( 2 - colRtl ) * ( size + gap );
		const y = row * ( size + gap );

		body += `<rect x="${ x }" y="${ y }" width="${ size }" height="${ size }" rx="10" fill="none" stroke="currentColor" stroke-opacity=".22" stroke-width="1.5"/>`;
		body += draw( x + size / 2, y + size / 2 );
	} );

	// الخلية الناقصة.
	const x = 0;
	const y = 2 * ( size + gap );
	body += `<rect x="${ x }" y="${ y }" width="${ size }" height="${ size }" rx="10" fill="currentColor" fill-opacity=".06" stroke="currentColor" stroke-opacity=".5" stroke-width="1.5" stroke-dasharray="5 4"/>`;
	body += `<text x="${ x + size / 2 }" y="${ y + size / 2 + 9 }" text-anchor="middle" font-size="28" font-weight="700" fill="currentColor" fill-opacity=".55">؟</text>`;

	const total = 3 * size + 2 * gap;

	return `<svg viewBox="-2 -2 ${ total + 4 } ${ total + 4 }" width="${ total }" height="${ total }" role="img" aria-label="${ label }" xmlns="http://www.w3.org/2000/svg">${ body }</svg>`;
}

function option( draw: ( cx: number, cy: number ) => string, label: string ): string {
	return `<svg viewBox="0 0 66 66" width="56" height="56" role="img" aria-label="${ label }" xmlns="http://www.w3.org/2000/svg">${ draw( 33, 33 ) }</svg>`;
}

const S = ( k: Shape, f: Fill = 'none' ) => ( cx: number, cy: number ) => shape( k, cx, cy, 17, f );
const D = ( n: number ) => ( cx: number, cy: number ) => dots( n, cx, cy );

