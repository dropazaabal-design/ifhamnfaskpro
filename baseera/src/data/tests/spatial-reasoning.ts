function netChoices( n: NetSpec ): Choice[] {
	const box = Math.max( ...n.options.flatMap( ( o ) => normalize( o ).flatMap( ( p ) => [ p[ 0 ] + 1, p[ 1 ] + 1 ] ) ) );

	return n.options.map( ( o, i ) => ( {
		label: `الشكل ${ i + 1 }`,
		correct: i === n.valid ? true : undefined,
		figure: draw( o, box, `الشكل ${ i + 1 }` ),
	} ) );
}

