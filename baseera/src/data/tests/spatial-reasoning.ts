/**
 * الاستدلال المكاني — تدوير ذهني وشبكات مكعّب، مرسومة من إحداثيات.
 *
 * كل شكل يُبنى من قائمة مربّعات، والتدوير والقلب عمليّتان على الإحداثيات،
 * لا رسم باليد. وtools/check-science.mjs يتحقّق من كل سؤال: أن الخيار
 * الصحيح وحده تدوير للأصل، وأن الأصل غير متناظر (وإلّا صارت صورة المرآة
 * تدويراً أيضاً)، وأن شبكة واحدة فقط تُطوى مكعّباً — بمحاكاة دحرجة مكعّب.
 */
export type Cell = [ number, number ];

/** 90° مع عقارب الساعة على الشاشة (المحور y إلى الأسفل). */
export const rotate = ( c: Cell[] ): Cell[] => c.map( ( [ x, y ] ) => [ -y, x ] );
export const mirror = ( c: Cell[] ): Cell[] => c.map( ( [ x, y ] ) => [ -x, y ] );
export const turns = ( c: Cell[], k: number ): Cell[] => ( k <= 0 ? c : turns( rotate( c ), k - 1 ) );

export function normalize( c: Cell[] ): Cell[] {
	const mx = Math.min( ...c.map( ( p ) => p[ 0 ] ) );
	const my = Math.min( ...c.map( ( p ) => p[ 1 ] ) );

	return c.map( ( [ x, y ] ): Cell => [ x - mx, y - my ] ).sort( ( a, b ) => a[ 1 ] - b[ 1 ] || a[ 0 ] - b[ 0 ] );
}

/** يرسم المربّعات في صندوق ثابت الحجم، كي تتساوى الخيارات في المقياس. */
function draw( cells: Cell[], box: number, label: string ): string {
	const n = normalize( cells );
	const w = Math.max( ...n.map( ( p ) => p[ 0 ] ) ) + 1;
	const h = Math.max( ...n.map( ( p ) => p[ 1 ] ) ) + 1;
	const s = 20;
	const ox = ( ( box - w ) * s ) / 2 + 4;
	const oy = ( ( box - h ) * s ) / 2 + 4;
	const rects = n
		.map( ( [ x, y ] ) => `<rect x="${ ox + x * s }" y="${ oy + y * s }" width="${ s }" height="${ s }" rx="2" fill="currentColor" fill-opacity=".22" stroke="currentColor" stroke-width="2"/>` )
		.join( '' );
	const size = box * s + 8;

	return `<svg viewBox="0 0 ${ size } ${ size }" role="img" aria-label="${ label }">${ rects }</svg>`;
}

export interface RotationSpec {
	shape: Cell[];
	/** عدد أرباع اللفّة للخيار الصحيح. */
	correct: number;
	/** موضع الصحيح بين الخيارات (0–3). */
	at: number;
	/** أرباع اللفّة لصور المرآة الثلاث. */
	mirrors: [ number, number, number ];
}

