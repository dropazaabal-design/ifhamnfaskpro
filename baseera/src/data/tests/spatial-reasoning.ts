const TURN_WORD = [ '', 'ربع لفّة مع عقارب الساعة', 'نصف لفّة', 'ربع لفّة عكس عقارب الساعة' ];

function rotationChoices( r: RotationSpec ): Choice[] {
	const box = 4;
	const out: Choice[] = r.mirrors.map( ( k, i ) => ( {
		label: '',
		figure: draw( turns( mirror( r.shape ), k ), box, `خيار ${ i + 1 }` ),
	} ) );

	out.splice( r.at, 0, { label: '', correct: true, figure: draw( turns( r.shape, r.correct ), box, '' ) } );

	return out.map( ( c, i ) => ( {
		...c,
		label: `الشكل ${ i + 1 }`,
		figure: c.figure!.replace( /aria-label="[^"]*"/, `aria-label="الشكل ${ i + 1 }"` ),
	} ) );
}

