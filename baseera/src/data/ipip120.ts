export interface FacetSpec {
	code: FacetCode;
	/** معرّف المقياس الفرعي في الاختبار. */
	id: string;
	name: string;
	about: string;
	/**
	 * يقلب اتّجاه الوجه: «الغضب» يصير «تهدئة الغضب». البنود نفسها،
	 * والثبات والانحراف لا يتغيّران بالقلب.
	 */
	flip?: boolean;
	higherIs: Subscale[ 'higherIs' ];
	/** الفئات الثلاث بالترتيب: 4–9، 10–14، 15–20. */
	bands: [ Omit<Band, 'upTo'>, Omit<Band, 'upTo'>, Omit<Band, 'upTo'> ];
}

/**
 * البنود متداخلة: بند من كل وجه بالتناوب، كما في الأداة الأصلية. تجميع
 * بنود الوجه الواحد متتالية يجعل المجيب يقرأ السؤال الرابع كتكرار للأوّل.
 */
export function facetItems( specs: FacetSpec[] ): Item[] {
	const out: Item[] = [];

	for ( let k = 0; k < 4; k++ ) {
		for ( const s of specs ) {
			const [ key, text ] = FACETS[ s.code ].items[ k ];
			const final = ( s.flip ? -key : key ) as 1 | -1;
			out.push( { id: `${ s.id.toLowerCase() }${ k + 1 }`, scale: s.id, key: final, text } );
		}
	}

	return out;
}

export function facetSubscale( s: FacetSpec ): Subscale {
	const f = FACETS[ s.code ];

	return {
		id: s.id,
		name: s.name,
		scoring: 'sum',
		min: 4,
		max: 20,
		alpha: f.alpha,
		sd: f.sd,
		paramsSource: `${ s.code } ${ f.en }: α ${ f.alpha.toFixed( 2 ) } من موقع IPIP (Johnson 2014، N = 619,150) · SD ${ f.sd } محسوب من بيانات Johnson المنشورة على OSF`,
		verified: true,
		higherIs: s.higherIs,
		about: s.about,
		bands: [
			{ upTo: 9, ...s.bands[ 0 ] },
			{ upTo: 14, ...s.bands[ 1 ] },
			{ upTo: 20, ...s.bands[ 2 ] },
		],
	};
}

