function stripLead(t) {
  return String(t || '').trim().replace(/^(كيف|توقّف عن|POV:)\s*/i, '');
}

/* ── استعلامات المكتبة ── */

function allTopics() {
  return TOPICS.concat(listCustomTopics());
}

function findTopic(id) {
  return allTopics().find(t => t.id === id) || null;
}

function filterTopics(axis, query) {
  const q = (query || '').trim();
  return allTopics().filter(t => {
    if (axis && axis !== 'all' && t.axis !== axis) return false;
    if (!q) return true;
    const hay = [t.title, t.hook, t.outro]
      .concat((t.points || []).map(p => p.head + ' ' + p.body))
      .join(' ');
    return hay.includes(q);
  });
}

/* يحوّل موضوعًا من المكتبة إلى مشروع جاهز في المحرّر */
function topicToProject(topic, baseProject) {
  const p = baseProject || newProject(topic.title);
  p.name  = topic.title;
  p.theme = topic.theme || p.theme;
  p.screens.hook = {
    badge: (HOOK_STYLES[topic.hookStyle] || HOOK_STYLES.pov).badge,
    text:  topic.hook || topic.title,
    sub:   topic.sub || '',
    bgImage: p.screens.hook.bgImage || null
  };
  p.screens.content = Object.assign({}, p.screens.content, {
    emoji:  topic.emoji || '📌',
    title:  topic.title,
    points: (topic.points || []).map(pt => ({ head:pt.head, body:pt.body })),
    outro:  topic.outro || '',
    cta:    topic.cta || CTA_TEMPLATES[0]
  });
  p.screens.flow = { text:'', auto:true };
  p.captionMeta = Object.assign({}, p.captionMeta, { category: axisToCategory(topic.axis) });
  return p;
}

/* ربط محور المكتبة بتصنيف الكابشن */
function axisToCategory(axis) {
  return ({
    haiba:'quwa', indibat:'adat', mal:'mal',
    wai:'wai', ilaqat:'ilaqat', dini:'dini'
  })[axis] || 'wai';
}
